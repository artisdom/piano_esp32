#!/usr/bin/env python3
"""Build the UI font subset and the matching Slint glyph list.

Slint's software renderer can only draw glyphs that are embedded at build
time, and it embeds exactly the characters that appear in `.slint` string
literals (plus ASCII). Song and folder names come from the SD card at run
time and are mostly Chinese, so this script:

  1. collects a character set: printable ASCII + Latin-1, general and CJK
     punctuation, full-width forms, all 3755 GB2312 level-1 hanzi (the
     common characters), and every character used in the MIDI library's
     file and folder names;
  2. subsets Noto Sans CJK SC Regular to that set -> ui/fonts/NotoSansSC-Piano.otf;
  3. writes ui/glyphs.slint holding the same characters in a string literal
     so slint-build embeds every one of them.

Needs fonttools (pip install fonttools). Re-run after adding songs whose
names use rarer characters:

  tools/make_font.py --library /path/to/midi
"""
import argparse, os, sys
from fontTools import subset, ttLib

ap = argparse.ArgumentParser()
ap.add_argument("--library", default=os.path.expanduser("~/w/piano/midi-piano/assets/midi"))
ap.add_argument("--font", default="/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc")
ap.add_argument("--family", default="Noto Sans CJK SC")
args = ap.parse_args()
here = os.path.dirname(os.path.abspath(__file__))
ui = os.path.join(here, "..", "ui")

chars = set(chr(c) for c in range(0x20, 0x7f))
chars |= set(chr(c) for c in range(0xa0, 0x100))
chars |= set(chr(c) for c in range(0x2010, 0x2040))   # dashes, quotes, bullets, …
chars |= set(chr(c) for c in range(0x3000, 0x3040))   # CJK punctuation
chars |= set(chr(c) for c in range(0xff01, 0xff5f))   # full-width forms
chars |= set("♪♫♩♬▶■●○◆★☆✓✔✕×÷←↑→↓·")
gb_l1 = set()
for hi in range(0xb0, 0xd8):
    for lo in range(0xa1, 0xff):
        try:
            gb_l1.add(bytes([hi, lo]).decode("gb2312"))
        except UnicodeDecodeError:
            pass
chars |= gb_l1
lib = set()
if os.path.isdir(args.library):
    for dp, dn, fn in os.walk(args.library):
        for n in dn + fn:
            lib |= set(n)
chars |= lib

# Pick the requested family out of the collection.
coll = ttLib.TTCollection(args.font)
index = None
for i, f in enumerate(coll.fonts):
    if f["name"].getDebugName(1) == args.family:
        index = i
if index is None:
    sys.exit(f"{args.family} not in {args.font}")
font = ttLib.TTFont(args.font, fontNumber=index)
cmap = font.getBestCmap()
missing = sorted(c for c in chars if ord(c) not in cmap and c.isprintable() and c != " ")
chars = sorted(c for c in chars if ord(c) in cmap)

opts = subset.Options()
opts.layout_features = []          # no shaping tables needed
opts.name_IDs = [0, 1, 2, 3, 4, 5, 6]
opts.hinting = False
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=[ord(c) for c in chars])
sub.subset(font)
out = os.path.join(ui, "fonts", "NotoSansSC-Piano.otf")
font.save(out)

lit = "".join(chars).replace("\\", "\\\\").replace('"', '\\"')
with open(os.path.join(ui, "glyphs.slint"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by tools/make_font.py — do not edit.\n")
    f.write("// Every character the UI can draw at run time (song/folder names come\n")
    f.write("// from the SD card), so slint-build embeds their glyphs.\n")
    f.write("export global Glyphs {\n")
    f.write(f'    out property <string> all: "{lit}";\n')
    f.write("}\n")
print(f"{len(chars)} glyphs ({len(gb_l1)} GB2312-L1, {len(lib)} from library) -> {out} "
      f"({os.path.getsize(out)//1024} KB); missing in font: {''.join(missing)!r}")

# ---- icon font -------------------------------------------------------------
# Font Awesome 4.7 (SIL OFL 1.1) glyphs used by ui/icons.slint. Slint's
# vector Path needs the renderer's `std` feature on this target, so icons
# are font glyphs instead.
ICONS = [0xf04b, 0xf04c, 0xf04d, 0xf021, 0xf07b, 0xf001, 0xf060, 0xf054, 0xf025,
         0xf19d, 0xf0e4, 0xf013, 0xf287, 0xf0eb, 0xf068, 0xf067, 0xf015, 0xf00c,
         0xf005, 0xf294, 0xf0a0, 0xf0e2, 0xf03a, 0xf0e7, 0xf011,
         0xf002, 0xf00d, 0xf01e, 0xf12d, 0xf1da, 0xf0ac, 0xf006, 0xf028]
fa_src = "/usr/share/fonts/truetype/font-awesome/fontawesome-webfont.ttf"
fa = ttLib.TTFont(fa_src)
sub = subset.Subsetter(opts)
sub.populate(unicodes=ICONS)
sub.subset(fa)
fa_out = os.path.join(ui, "fonts", "fa-icons.ttf")
fa.save(fa_out)
print(f"{len(ICONS)} icons -> {fa_out} ({os.path.getsize(fa_out)} B)")

# ---- pinyin table for song search -------------------------------------------
# Song search on the Tab5 types Latin letters; each hanzi in the glyph set
# gets its (context-free, most common) toneless pinyin so titles can be
# matched by full pinyin ("xiaoyanzi") or initials ("xyz"). Needs pypinyin.
try:
    from pypinyin import lazy_pinyin
except ImportError:
    sys.exit("pip install pypinyin  (needed for the pinyin search table)")
rows = []
for c in chars:
    if "㐀" <= c <= "鿿":
        py = lazy_pinyin(c)[0]
        if py.isascii() and py.isalpha():
            rows.append((c, py.replace("ü", "v")))
core = os.path.join(here, "..", "..", "piano-core", "src", "pinyin_table.rs")
with open(core, "w", encoding="utf-8") as f:
    f.write("// GENERATED by firmware/tab5/tools/make_font.py (pypinyin) — do not edit.\n")
    f.write("// Toneless pinyin of every hanzi the UI font can draw, sorted by char.\n")
    f.write("pub static PINYIN: &[(char, &str)] = &[\n")
    for c, py in rows:
        f.write(f"    ('{c}', \"{py}\"),\n")
    f.write("];\n")
print(f"{len(rows)} pinyin entries -> {core}")

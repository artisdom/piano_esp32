#!/usr/bin/env python3
"""Export the sheet-music symbols from Noto Music as SVG images.

The Play page's sheet view draws clefs, accidentals, note heads and rests.
Importing the music font into Slint would re-embed every CJK character of
the UI a second time (slint-build gives each font the whole character set,
borrowing missing glyphs from system fallback fonts: +2.4 MB), so the 13
glyphs become SVGs instead, rasterised at build time and tinted at run time.

Writes ui/sheet/<name>.svg (sized for a 9 px staff space = 36 px em) and
src/ui/glyph_boxes.rs (each glyph's box in font units relative to its
origin; baseline = the staff's bottom line, 250 units = one staff space).

Needs fonttools:  tools/make_music_glyphs.py [--font NotoMusic-Regular.ttf]
"""
import argparse, os
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

# Order = piano_core::notation::Glyph::index().
GLYPHS = [
    ("gclef", 0x1D11E), ("fclef", 0x1D122), ("sharp", 0x266F), ("flat", 0x266D),
    ("natural", 0x266E), ("head-black", 0x1D158), ("head-half", 0x1D157),
    ("head-whole", 0x1D15D), ("rest-whole", 0x1D13B), ("rest-half", 0x1D13C),
    ("rest-quarter", 0x1D13D), ("rest-8", 0x1D13E), ("rest-16", 0x1D13F),
]
EM_PX = 36.0  # 4 staff spaces of 9 px

ap = argparse.ArgumentParser()
ap.add_argument("--font", default="/usr/share/fonts/truetype/noto/NotoMusic-Regular.ttf")
args = ap.parse_args()
here = os.path.dirname(os.path.abspath(__file__))
out_dir = os.path.join(here, "..", "ui", "sheet")
os.makedirs(out_dir, exist_ok=True)

font = TTFont(args.font)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upem = font["head"].unitsPerEm
boxes = []
for name, cp in GLYPHS:
    g = gs[cmap[cp]]
    bp = BoundsPen(gs)
    g.draw(bp)
    x0, y0, x1, y1 = bp.bounds
    # A little room so antialiasing is not clipped.
    pad = 8
    x0, y0, x1, y1 = x0 - pad, y0 - pad, x1 + pad, y1 + pad
    sp = SVGPathPen(gs)
    g.draw(sp)
    w, h = x1 - x0, y1 - y0
    scale = EM_PX / upem
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * scale:.2f}" height="{h * scale:.2f}" '
        f'viewBox="{x0} {-y1} {w} {h}"><path transform="scale(1,-1)" d="{sp.getCommands()}" fill="#000"/></svg>\n'
    )
    with open(os.path.join(out_dir, name + ".svg"), "w") as f:
        f.write(svg)
    boxes.append((name, x0, y0, x1, y1))

with open(os.path.join(here, "..", "src", "ui", "glyph_boxes.rs"), "w") as f:
    f.write("// GENERATED by tools/make_music_glyphs.py — do not edit.\n")
    f.write("// Music glyph boxes in font units (x0, y0, x1, y1), y up from the baseline;\n")
    f.write("// order = piano_core::notation::Glyph::index(), images in ui/sheet/.\n")
    f.write(f"const GLYPH_UPEM: f32 = {upem}.0;\n")
    f.write(f"const GLYPH_BOXES: [(f32, f32, f32, f32); {len(boxes)}] = [\n")
    for name, x0, y0, x1, y1 in boxes:
        f.write(f"    ({x0}.0, {y0}.0, {x1}.0, {y1}.0), // {name}\n")
    f.write("];\n")
print(f"{len(boxes)} glyphs -> {out_dir}")
